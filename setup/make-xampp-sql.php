<?php

declare(strict_types=1);

/**
 * Builds database/xampp/bhsystem-xampp.sql = schema.sql + seed.sql in one
 * file for XAMPP (MariaDB). It creates the `bhsystem` database itself, so it
 * can be imported in phpMyAdmin without selecting a database first.
 *
 *   php setup/make-xampp-sql.php
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$dir = __DIR__ . '/../database';

$out = "-- ============================================================================\n"
    . "-- Boarding House Rental System - IMPORT FILE FOR XAMPP (MariaDB / phpMyAdmin)\n"
    . "-- Generated by setup/make-xampp-sql.php from database/schema.sql + seed.sql.\n"
    . "-- phpMyAdmin > Import > choose this file > Import. No database needs to be\n"
    . "-- selected first: it creates `bhsystem` itself.\n"
    . "-- WARNING: re-importing drops and recreates every table (all data is reset).\n"
    . "-- Demo logins: admin@bhrental.local / Admin@12345, landlord1@bhrental.local /\n"
    . "-- Demo@12345, tenant1@bhrental.local / Demo@12345 (local use only).\n"
    . "-- ============================================================================\n\n"
    . (string) file_get_contents($dir . '/schema.sql')
    . "\n\n-- ---------------------------------------------------------------- demo data\n\n"
    . (string) file_get_contents($dir . '/seed.sql');

if (!is_dir($dir . '/xampp')) {
    mkdir($dir . '/xampp', 0755, true);
}
file_put_contents($dir . '/xampp/bhsystem-xampp.sql', $out);
echo 'Created database/xampp/bhsystem-xampp.sql (' . round(strlen($out) / 1024) . " KB)\n";
